// Regenerates src/shared/readability-source.ts from the installed @mozilla/readability (ADR-026).
// The reader runs Readability inside pages (isolated world on the desktop, injectJavaScript on the
// phone), so it is needed as source text; a generated module works for both bundlers (Vite, Metro).
// Run after updating the package: `node scripts/gen-readability.mjs` (a unit test checks it is in sync).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dir = dirname(require.resolve("@mozilla/readability/package.json"));
const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const read = (name) => readFileSync(join(dir, name), "utf8");

export function generate() {
  return [
    `// Generated by scripts/gen-readability.mjs from @mozilla/readability ${version}: do not edit.`,
    "// Readability: Copyright (c) 2010 Arc90 Inc, Apache License 2.0 (see the package's LICENSE.md).",
    "",
    "/** `Readability.js`: defines `function Readability(doc, options)`. */",
    `export const READABILITY_SOURCE = ${JSON.stringify(read("Readability.js"))};`,
    "",
    "/** `Readability-readerable.js`: defines `function isProbablyReaderable(doc, options)`. */",
    `export const READERABLE_SOURCE = ${JSON.stringify(read("Readability-readerable.js"))};`,
    "",
  ].join("\n");
}

export const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "shared", "readability-source.ts");

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUTPUT, generate());
