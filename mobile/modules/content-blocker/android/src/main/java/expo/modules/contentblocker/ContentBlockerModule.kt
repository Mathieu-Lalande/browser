package expo.modules.contentblocker

import android.net.Uri
import android.os.Handler
import android.os.Looper
import android.util.Log
import android.webkit.WebResourceRequest
import android.webkit.WebResourceResponse
import android.webkit.WebView
import expo.modules.kotlin.modules.Module
import expo.modules.kotlin.modules.ModuleDefinition
import java.io.ByteArrayInputStream
import java.util.Collections
import java.util.WeakHashMap
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.Executors
import java.util.function.BiFunction

/**
 * Content blocker for Android (ADR-051): every sub-resource request of every react-native-webview
 * goes through `shouldInterceptRequest`, where the bundled index (`assets/blocklists/network.json`,
 * generated by `scripts/build-blocklists.mjs`) decides; a blocked request gets an empty 204.
 *
 * react-native-webview has no hook for it. A small patch (`patches/react-native-webview+<version>.patch`)
 * adds to its `RNCWebViewClient` a static `requestInterceptor` consulted first by a new
 * `shouldInterceptRequest`; this module sets it by reflection, so neither side depends on the other
 * at compile time (without the patch, the module logs it and blocks nothing).
 *
 * The page of a request: `shouldInterceptRequest` runs off the UI thread, where `WebView.getUrl()`
 * may not be called, so each WebView's last main-frame request is remembered instead.
 * Blocked requests are reported to JavaScript in batches (`onBlocked`: page host, blocked host, count).
 */
class ContentBlockerModule : Module() {
  private val pages: MutableMap<WebView, String> = Collections.synchronizedMap(WeakHashMap())
  private val pending = ConcurrentHashMap<String, Int>()
  private val main = Handler(Looper.getMainLooper())
  private var flushScheduled = false

  @Volatile private var matcher: NetworkMatcher? = null
  @Volatile private var enabled = true
  @Volatile private var allowlist: Set<String> = emptySet()

  private val interceptor = BiFunction<WebView, WebResourceRequest, WebResourceResponse?> { view, request -> intercept(view, request) }

  override fun definition() = ModuleDefinition {
    Name("ContentBlocker")
    Events("onBlocked")

    Constant("counts") { true }

    OnCreate {
      install(interceptor)
      Executors.newSingleThreadExecutor().execute { load() }
    }

    OnDestroy {
      install(null)
    }

    AsyncFunction("apply") { enabled: Boolean, allowlist: List<String> ->
      this@ContentBlockerModule.allowlist = allowlist.map { it.lowercase() }.toSet()
      this@ContentBlockerModule.enabled = enabled
      if (enabled) matcher?.size ?: 0 else 0
    }
  }

  private fun load() {
    try {
      val context = appContext.reactContext ?: return
      val json = context.assets.open("blocklists/network.json").bufferedReader().use { it.readText() }
      matcher = NetworkMatcher.parse(json)
    } catch (error: Exception) {
      Log.w(TAG, "No blocklist: ${error.message}")
    }
  }

  private fun install(value: BiFunction<WebView, WebResourceRequest, WebResourceResponse?>?) {
    try {
      Class.forName("com.reactnativecommunity.webview.RNCWebViewClient").getField("requestInterceptor").set(null, value)
    } catch (error: Exception) {
      Log.w(TAG, "react-native-webview is not patched (patch-package): no request blocking. ${error.message}")
    }
  }

  private fun intercept(view: WebView, request: WebResourceRequest): WebResourceResponse? {
    val url = request.url
    val host = url.host?.lowercase() ?: return null
    if (url.scheme != "http" && url.scheme != "https") return null
    if (request.isForMainFrame) {
      pages[view] = host
      return null
    }
    val current = matcher ?: return null
    if (!enabled) return null
    val pageHost = pages[view] ?: ""
    if (pageHost.isNotEmpty() && allowlist.any { NetworkMatcher.hostMatches(pageHost, it) }) return null
    if (!current.blocks(host, pathOf(url), pageHost)) return null
    report(pageHost, host)
    return WebResourceResponse("text/plain", "utf-8", 204, "No Content", emptyMap(), ByteArrayInputStream(ByteArray(0)))
  }

  private fun pathOf(url: Uri): String {
    val path = url.encodedPath ?: "/"
    val query = url.encodedQuery
    return if (query != null) "$path?$query" else path
  }

  private fun report(pageHost: String, host: String) {
    pending.merge("$pageHost $host", 1, Int::plus)
    main.post {
      if (flushScheduled) return@post
      flushScheduled = true
      main.postDelayed({ flush() }, FLUSH_MS)
    }
  }

  private fun flush() {
    flushScheduled = false
    val events = pending.keys.toList().mapNotNull { key ->
      val count = pending.remove(key) ?: return@mapNotNull null
      val (page, tracker) = key.split(' ', limit = 2)
      mapOf("page" to page, "tracker" to tracker, "count" to count)
    }
    if (events.isNotEmpty()) sendEvent("onBlocked", mapOf("events" to events))
  }

  companion object {
    private const val TAG = "ContentBlocker"
    private const val FLUSH_MS = 1500L
  }
}
